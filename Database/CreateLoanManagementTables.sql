/*
  Loan Management System
  Database tables: Customers and EMICollections only.
  LoanAccountNo is generated by SQL Server sequence with LN prefix.
*/

IF DB_ID(N'LoanManagementDB') IS NULL
    CREATE DATABASE LoanManagementDB;
GO

USE LoanManagementDB;
GO

IF OBJECT_ID(N'dbo.EMICollections', N'U') IS NOT NULL
    DROP TABLE dbo.EMICollections;
GO

IF OBJECT_ID(N'dbo.Customers', N'U') IS NOT NULL
    DROP TABLE dbo.Customers;
GO

IF OBJECT_ID(N'dbo.Seq_LoanAccountNo', N'SO') IS NOT NULL
    DROP SEQUENCE dbo.Seq_LoanAccountNo;
GO

CREATE SEQUENCE dbo.Seq_LoanAccountNo
    AS BIGINT
    START WITH 1
    INCREMENT BY 1;
GO

CREATE TABLE dbo.Customers
(
    LoanAccountNo VARCHAR(20) NOT NULL
        CONSTRAINT DF_Customers_LoanAccountNo
        DEFAULT
        (
            'LN' + RIGHT(
                '000000000000000000' +
                CONVERT(VARCHAR(20), NEXT VALUE FOR dbo.Seq_LoanAccountNo),
                18
            )
        ),
    CustomerName NVARCHAR(150) NOT NULL,
    AadhaarNumber VARCHAR(12) NOT NULL,
    PANNumber VARCHAR(10) NOT NULL,
    SignatureImagePath NVARCHAR(500) NULL,
    PhotoPath NVARCHAR(500) NULL,
    AadhaarDocumentPath NVARCHAR(500) NULL,
    PANDocumentPath NVARCHAR(500) NULL,
    ReferredPerson NVARCHAR(150) NULL,
    ReferredContactNo VARCHAR(15) NULL,
    PrimaryContactNo VARCHAR(15) NOT NULL,
    SecondaryContactNo VARCHAR(15) NULL,
    LoanAmount DECIMAL(18,2) NOT NULL,
    EMIAmount DECIMAL(18,2) NOT NULL,
    InstallmentCount INT NOT NULL
        CONSTRAINT DF_Customers_InstallmentCount DEFAULT (10),
    IsLive BIT NOT NULL
        CONSTRAINT DF_Customers_IsLive DEFAULT (1),
    CreatedBy NVARCHAR(100) NOT NULL,
    CreatedOn DATETIME2(0) NOT NULL
        CONSTRAINT DF_Customers_CreatedOn DEFAULT (SYSDATETIME()),
    ModifiedBy NVARCHAR(100) NULL,
    ModifiedDate DATETIME2(0) NULL,
    Remarks NVARCHAR(1000) NOT NULL,

    CONSTRAINT PK_Customers PRIMARY KEY (LoanAccountNo),
    CONSTRAINT CK_Customers_LoanAmount CHECK (LoanAmount > 0),
    CONSTRAINT CK_Customers_EMIAmount CHECK (EMIAmount > 0),
    CONSTRAINT CK_Customers_InstallmentCount CHECK (InstallmentCount = 10)
);
GO

CREATE INDEX IX_Customers_AadhaarNumber ON dbo.Customers(AadhaarNumber);
CREATE INDEX IX_Customers_PANNumber ON dbo.Customers(PANNumber);
GO

CREATE TABLE dbo.EMICollections
(
    CollectionId BIGINT IDENTITY(1,1) NOT NULL,
    LoanAccountNo VARCHAR(20) NOT NULL,
    InstallmentNumber INT NOT NULL,
    EMIAmount DECIMAL(18,2) NOT NULL,
    PenaltyAmount DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_EMICollections_PenaltyAmount DEFAULT (0),
    TotalAmount AS (EMIAmount + PenaltyAmount) PERSISTED,
    CollectionDate DATETIME2(0) NOT NULL
        CONSTRAINT DF_EMICollections_CollectionDate DEFAULT (SYSDATETIME()),
    CreatedBy NVARCHAR(100) NOT NULL,
    CreatedOn DATETIME2(0) NOT NULL
        CONSTRAINT DF_EMICollections_CreatedOn DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_EMICollections PRIMARY KEY (CollectionId),
    CONSTRAINT FK_EMICollections_Customers
        FOREIGN KEY (LoanAccountNo)
        REFERENCES dbo.Customers(LoanAccountNo),
    CONSTRAINT CK_EMICollections_EMIAmount CHECK (EMIAmount > 0),
    CONSTRAINT CK_EMICollections_PenaltyAmount CHECK (PenaltyAmount >= 0),
    CONSTRAINT CK_EMICollections_InstallmentNumber CHECK (InstallmentNumber > 0),
    CONSTRAINT UX_EMICollections_Loan_Installment UNIQUE (LoanAccountNo, InstallmentNumber)
);
GO

PRINT 'LoanManagementDB created with Customers and EMICollections tables.';
GO
